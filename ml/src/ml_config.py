def norm_reference(type_id):
    """Основная норма типа: 'Документ, пункт'. Пусто, если нормы нет."""
    t = TYPES.get(type_id)
    if not t or not t.get("norms"):
        return ""
    n = NORMS.get(t["norms"][0])
    if not n:
        return ""
    return f"{SHORT_TITLES.get(n['doc'], DOCS[n['doc']]['title'])}, {n['clause']}"


