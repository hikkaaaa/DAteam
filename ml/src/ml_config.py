def _load():
    with open(TYPES_PATH, encoding="utf-8") as f:
        types = {t["id"]: t for t in yaml.safe_load(f)["types"]}
    with open(NORMS_PATH, encoding="utf-8") as f:
        raw = yaml.safe_load(f)
    return types, {n["id"]: n for n in raw["norms"]}, raw["documents"]


