def _type_lines():
    lines = []
    for tid in PROMPT_TYPE_IDS:
        t = TYPES[tid]
        criterion = t["criterion"].replace("≥ N с", "несколько секунд")
        line = f"- {tid} — {t['type']}: {criterion}"
        note = t.get("note") or ""
        if note and "ТЗ" not in note and "config" not in note:  # служебные заметки модели не показываем
            line += f" Важно: {note}"
        if tid in EXTRA_NOTES:
            line += f" Уточнение: {EXTRA_NOTES[tid]}"
        lines.append(line)
    lines.append(f"- {OTHER_ID} — {OTHER_TYPE}: иное явно подозрительное действие с наличными или ценностями, "
                 "которого нет в списке (только если оно очевидно).")
    return lines


